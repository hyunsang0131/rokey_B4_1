def _xyz(name, default):
    v = os.environ.get(name)
    if v in (None, ''):
        return default
    vals = [float(s) for s in v.replace(',', ' ').split()]
    if len(vals) != 3:
        raise ValueError(f'{name} 는 x,y,z 3개여야 합니다: {v!r}')
    return vals


